#!/usr/bin/env bash
# Per-user install of the native driver, for any distro and init system.
#
#   scripts/install-user.sh [install|uninstall] [options]
#
# install (default):
#   - builds iot_driver (release) and copies it to ~/.local/bin
#   - adds a `monsgeek` launcher there: no arguments opens the TUI, anything else
#     is passed to iot_driver (`monsgeek info`, `monsgeek led`, ...)
#   - installs the device database to $XDG_DATA_HOME/akko
#   - adds an app-menu entry that opens the TUI in a terminal
#   - makes the server (`iot_driver serve`) start automatically, and starts it now
#   - installs the udev rules with sudo, only if they are missing or outdated
#
# How the server is started automatically depends on the init system (detected,
# or forced with --autostart):
#   systemd  systemd user service; starts at login, restarts on failure. No sudo.
#   runit    system service running as you (Void: /etc/sv, Artix: /etc/runit/sv);
#            starts at boot, restarts on failure. Needs sudo once.
#   openrc   /etc/init.d service running as you, supervised; starts at boot.
#            Needs sudo once.
#   xdg      XDG autostart entry (~/.config/autostart). Run by desktop environments
#            (KDE, GNOME, XFCE, ...) but NOT by bare window managers (awesome, i3,
#            sway, Hyprland, ...): there, add the printed command to the WM startup.
#   none     no automatic start.
#
# uninstall: stops the server and removes everything above except the udev rules.
#
# Options:
#   --autostart=MODE  auto (default), systemd, runit, openrc, xdg or none
#   --no-build        install the existing target/release binary without rebuilding
#   --no-start        do not start the server now (runit still starts an enabled
#                     service right away; that is how runit works)
#   --no-udev         never touch the udev rules
#
# Env knobs:
#   BIN_DIR          launcher/binary destination (default ~/.local/bin)
#   XDG_DATA_HOME    data + app-menu root (default ~/.local/share)
#   XDG_CONFIG_HOME  autostart / systemd user unit root (default ~/.config)
#   XDG_STATE_HOME   server log root (default ~/.local/state)
#   SKIP_REFRESH     default 1; set to 0 to be offered a device DB refresh first
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DRIVER_DIR="$REPO_ROOT/iot_driver_linux"
BUILT_BIN="$DRIVER_DIR/target/release/iot_driver"
RULES_SRC="$REPO_ROOT/udev/99-monsgeek.rules"

# A relative XDG_* value is invalid per the spec and must be ignored.
xdg_dir() {
  case "${1:-}" in
    /*) printf '%s\n' "$1" ;;
    *) printf '%s\n' "$2" ;;
  esac
}

BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"
DATA_HOME="$(xdg_dir "${XDG_DATA_HOME:-}" "$HOME/.local/share")"
CONFIG_HOME="$(xdg_dir "${XDG_CONFIG_HOME:-}" "$HOME/.config")"
STATE_HOME="$(xdg_dir "${XDG_STATE_HOME:-}" "$HOME/.local/state")"

DATA_DIR="$DATA_HOME/akko"
APP_DIR="$DATA_HOME/applications"
LOG_DIR="$STATE_HOME/akko"
LOG_FILE="$LOG_DIR/iot_driver.log"

BIN="$BIN_DIR/iot_driver"
LAUNCHER="$BIN_DIR/monsgeek"
# The desktop file id doubles as the ScreenCast portal app id (see screen_capture.rs),
# so it keeps the packaging name instead of a shorter one.
DESKTOP_ID="solutions.echtzeit.akko_keyboard_driver.desktop"
DESKTOP_FILE="$APP_DIR/$DESKTOP_ID"
SERVER_PORT=3814

# Every autostart artifact uses this name, so any one of them can be found and
# removed again when switching modes or uninstalling.
SERVICE=monsgeek-iot-driver
XDG_AUTOSTART_FILE="$CONFIG_HOME/autostart/$SERVICE.desktop"
SYSTEMD_UNIT="$CONFIG_HOME/systemd/user/$SERVICE.service"
OPENRC_SCRIPT="/etc/init.d/$SERVICE"
# Marks files this script generated, so it never removes a same-named file it did
# not write.
MARKER="Generated by monsgeek-akko-linux scripts/install-user.sh"

ACTION=install
BUILD=1
START=1
UDEV=1
AUTOSTART=auto

step() { printf '\n==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }

# Quote a path for a .desktop Exec key (the spec requires double quotes when it has
# reserved characters; quoting always is valid and simpler).
desktop_quote() {
  local s="$1"
  s="${s//\\/\\\\\\\\}"
  s="${s//\"/\\\"}"
  s="${s//\`/\\\`}"
  s="${s//\$/\\\$}"
  printf '"%s"' "$s"
}

# Single-quote a value for /bin/sh.
sh_quote() {
  printf "'%s'" "${1//\'/\'\\\'\'}"
}

is_ours() { [ -f "$1" ] && grep -q "$MARKER" "$1" 2>/dev/null; }

# ---------------------------------------------------------------------------
# Init system detection
# ---------------------------------------------------------------------------

# runit service layout: "<service dir> <enabled dir>", or nothing if unknown.
runit_layout() {
  if [ -d /etc/sv ] && [ -d /var/service ]; then
    echo "/etc/sv /var/service" # Void
  elif [ -d /etc/runit/sv ] && [ -d /run/runit/service ]; then
    echo "/etc/runit/sv /run/runit/service" # Artix
  fi
}

detect_autostart() {
  local pid1
  pid1="$(cat /proc/1/comm 2>/dev/null || true)"
  # /run/systemd/system is how sd_booted() tells systemd is PID 1; the user manager
  # check catches containers and sessions without one.
  if [ -d /run/systemd/system ] && systemctl --user show-environment >/dev/null 2>&1; then
    echo systemd
  elif [ "$pid1" = runit ] && command -v sv >/dev/null 2>&1 && [ -n "$(runit_layout)" ]; then
    echo runit
  elif [ -d /run/openrc ] && command -v rc-service >/dev/null 2>&1 && [ -x /sbin/openrc-run ]; then
    echo openrc
  else
    echo xdg
  fi
}

# ---------------------------------------------------------------------------
# Service file rendering (pure: they only print)
# ---------------------------------------------------------------------------

render_xdg_autostart() {
  cat <<EOF
[Desktop Entry]
# $MARKER
Type=Application
Name=MonsGeek IOT Driver
Comment=Local gRPC driver (127.0.0.1:$SERVER_PORT) for the web.monsgeek.com configurator
Exec=$(desktop_quote "$BIN") serve
Terminal=false
NoDisplay=true
X-GNOME-Autostart-enabled=true
EOF
}

render_systemd_unit() {
  # systemd expands %-specifiers in these values; %% is a literal %.
  local bin="${BIN//%/%%}" data_home="${DATA_HOME//%/%%}"
  cat <<EOF
# $MARKER
[Unit]
Description=MonsGeek/Akko IOT driver (gRPC server for web.monsgeek.com)

[Service]
ExecStart="$bin" serve
Environment="XDG_DATA_HOME=$data_home"
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
EOF
}

render_runit_run() {
  local user group
  user="$(id -un)"
  group="$(id -gn)"
  cat <<EOF
#!/bin/sh
# $MARKER
# Runs the server as $user, from boot.
exec 2>&1
cd $(sh_quote "$HOME") || exit 1
exec chpst -u $(sh_quote "$user:$group") env HOME=$(sh_quote "$HOME") XDG_DATA_HOME=$(sh_quote "$DATA_HOME") $(sh_quote "$BIN") serve
EOF
}

render_runit_log_run() {
  cat <<EOF
#!/bin/sh
# $MARKER
# svlogd rotates the log; read it with: tail -f $LOG_DIR/current
exec chpst -u $(sh_quote "$(id -un):$(id -gn)") svlogd -tt $(sh_quote "$LOG_DIR")
EOF
}

render_openrc_script() {
  cat <<EOF
#!/sbin/openrc-run
# $MARKER
description="MonsGeek/Akko IOT driver (gRPC server for web.monsgeek.com), as $(id -un)"
supervisor=supervise-daemon
command=$(sh_quote "$BIN")
command_args="serve"
command_user=$(sh_quote "$(id -un):$(id -gn)")
directory=$(sh_quote "$HOME")
output_log=$(sh_quote "$LOG_FILE")
error_log=$(sh_quote "$LOG_FILE")
respawn_delay=2
supervise_daemon_args="--env HOME=$(sh_quote "$HOME") --env XDG_DATA_HOME=$(sh_quote "$DATA_HOME")"

depend() {
	need localmount
	after udev
}
EOF
}

# ---------------------------------------------------------------------------
# Server process helpers
# ---------------------------------------------------------------------------

server_pids() {
  pgrep -u "$(id -u)" -f '(^|/)iot_driver (serve|server)( |$)' || true
}

# Kill server processes no service manager owns (e.g. one started by hand or by an
# earlier xdg-mode install); a second server could not bind the port.
kill_strays() {
  local pids
  pids="$(server_pids)"
  [ -z "$pids" ] && return 0
  echo "Stopping running server (pid $(echo $pids))..."
  # shellcheck disable=SC2086
  kill $pids 2>/dev/null || true
  for _ in $(seq 50); do
    [ -z "$(server_pids)" ] && return 0
    sleep 0.1
  done
  warn "server did not exit after 5s; sending SIGKILL."
  # shellcheck disable=SC2086
  kill -9 $pids 2>/dev/null || true
}

port_listening() {
  if command -v ss >/dev/null 2>&1; then
    ss -Hltn "sport = :$SERVER_PORT" 2>/dev/null | grep -q .
  else
    (exec 3<>"/dev/tcp/127.0.0.1/$SERVER_PORT") 2>/dev/null
  fi
}

wait_listening() {
  local log_hint="$1"
  for _ in $(seq 100); do
    if port_listening; then
      echo "Server listening on 127.0.0.1:$SERVER_PORT (log: $log_hint)"
      return 0
    fi
    sleep 0.1
  done
  warn "server is not listening on port $SERVER_PORT after 10s (log: $log_hint)"
  return 1
}

start_detached() {
  mkdir -p "$LOG_DIR"
  # setsid detaches it from this terminal so it survives the installer exiting;
  # exec leaves no shell behind holding the installer's stdout open. cd $HOME so
  # it runs exactly as the autostart entry would.
  (cd "$HOME" && exec setsid "$BIN" serve) </dev/null >"$LOG_FILE" 2>&1 &
  wait_listening "$LOG_FILE" || { tail -n 20 "$LOG_FILE" >&2 || true; }
}

need_sudo() {
  command -v sudo >/dev/null 2>&1 && return 0
  warn "sudo not found; cannot install the $1 service. Use --autostart=xdg or run as a user with sudo."
  exit 1
}

# ---------------------------------------------------------------------------
# Per-mode install / remove
# ---------------------------------------------------------------------------

install_xdg() {
  mkdir -p "$(dirname "$XDG_AUTOSTART_FILE")"
  render_xdg_autostart >"$XDG_AUTOSTART_FILE"
  chmod 644 "$XDG_AUTOSTART_FILE"
  echo "  $XDG_AUTOSTART_FILE"
  if [ "$START" = 1 ]; then
    kill_strays
    start_detached
  fi
  if [ -z "${XDG_CURRENT_DESKTOP:-}" ]; then
    echo
    echo "NOTE: no desktop environment detected (XDG_CURRENT_DESKTOP is empty). Bare window"
    echo "managers (awesome, i3, sway, Hyprland, bspwm, ...) do not run XDG autostart entries."
    echo "Add this command to your WM's startup instead:"
    echo "  $BIN serve"
  fi
}

remove_xdg() {
  if is_ours "$XDG_AUTOSTART_FILE"; then
    rm -f "$XDG_AUTOSTART_FILE"
    echo "  removed $XDG_AUTOSTART_FILE"
  fi
  # Pre-marker installs used this exact content without the marker line.
  if [ -f "$XDG_AUTOSTART_FILE" ] && grep -q '^Name=MonsGeek IOT Driver$' "$XDG_AUTOSTART_FILE"; then
    rm -f "$XDG_AUTOSTART_FILE"
    echo "  removed $XDG_AUTOSTART_FILE"
  fi
}

install_systemd() {
  mkdir -p "$(dirname "$SYSTEMD_UNIT")"
  render_systemd_unit >"$SYSTEMD_UNIT"
  chmod 644 "$SYSTEMD_UNIT"
  echo "  $SYSTEMD_UNIT"
  systemctl --user daemon-reload
  systemctl --user stop "$SERVICE" 2>/dev/null || true
  kill_strays
  if [ "$START" = 1 ]; then
    systemctl --user enable "$SERVICE"
    systemctl --user restart "$SERVICE"
    wait_listening "journalctl --user -u $SERVICE" || true
  else
    systemctl --user enable "$SERVICE"
  fi
}

remove_systemd() {
  is_ours "$SYSTEMD_UNIT" || return 0
  if command -v systemctl >/dev/null 2>&1; then
    systemctl --user disable --now "$SERVICE" 2>/dev/null || true
  fi
  rm -f "$SYSTEMD_UNIT"
  command -v systemctl >/dev/null 2>&1 && systemctl --user daemon-reload 2>/dev/null || true
  echo "  removed $SYSTEMD_UNIT"
}

install_runit() {
  need_sudo runit
  local layout sv_dir enabled_dir tmp
  layout="$(runit_layout)"
  sv_dir="${layout% *}"
  enabled_dir="${layout#* }"
  mkdir -p "$LOG_DIR"
  tmp="$(mktemp -d)"
  render_runit_run >"$tmp/run"
  render_runit_log_run >"$tmp/log-run"
  echo "Installing the runit service needs sudo."
  sudo install -D -m 755 "$tmp/run" "$sv_dir/$SERVICE/run"
  sudo install -D -m 755 "$tmp/log-run" "$sv_dir/$SERVICE/log/run"
  rm -rf "$tmp"
  echo "  $sv_dir/$SERVICE"
  if [ -L "$enabled_dir/$SERVICE" ]; then
    sudo sv down "$SERVICE" >/dev/null 2>&1 || true
    kill_strays
    sudo sv up "$SERVICE"
  else
    kill_strays
    sudo ln -s "$sv_dir/$SERVICE" "$enabled_dir/$SERVICE"
    echo "  enabled in $enabled_dir"
  fi
  # runsvdir scans for new services every 5s.
  wait_listening "$LOG_DIR/current" || true
}

remove_runit() {
  local layout sv_dir enabled_dir
  layout="$(runit_layout)"
  [ -n "$layout" ] || return 0
  sv_dir="${layout% *}"
  enabled_dir="${layout#* }"
  is_ours "$sv_dir/$SERVICE/run" || return 0
  need_sudo runit
  echo "Removing the runit service needs sudo."
  sudo sv down "$SERVICE" >/dev/null 2>&1 || true
  sudo rm -f "$enabled_dir/$SERVICE"
  sudo rm -rf "$sv_dir/$SERVICE"
  echo "  removed $sv_dir/$SERVICE"
}

install_openrc() {
  need_sudo openrc
  local tmp
  mkdir -p "$LOG_DIR"
  # Created as you, so the log stays writable whether supervise-daemon opens it
  # before or after dropping to your user.
  touch "$LOG_FILE"
  tmp="$(mktemp)"
  render_openrc_script >"$tmp"
  echo "Installing the OpenRC service needs sudo."
  sudo install -m 755 "$tmp" "$OPENRC_SCRIPT"
  rm -f "$tmp"
  echo "  $OPENRC_SCRIPT"
  sudo rc-service "$SERVICE" stop >/dev/null 2>&1 || true
  kill_strays
  sudo rc-update add "$SERVICE" default
  if [ "$START" = 1 ]; then
    sudo rc-service "$SERVICE" start
    wait_listening "$LOG_FILE" || true
  fi
}

remove_openrc() {
  is_ours "$OPENRC_SCRIPT" || return 0
  need_sudo openrc
  echo "Removing the OpenRC service needs sudo."
  sudo rc-service "$SERVICE" stop >/dev/null 2>&1 || true
  sudo rc-update del "$SERVICE" default >/dev/null 2>&1 || true
  sudo rm -f "$OPENRC_SCRIPT"
  echo "  removed $OPENRC_SCRIPT"
}

# Remove every autostart artifact except the one for KEEP (a mode name, or "").
remove_autostart_except() {
  local keep="$1" mode
  for mode in xdg systemd runit openrc; do
    [ "$mode" = "$keep" ] || "remove_$mode"
  done
}

# ---------------------------------------------------------------------------
# udev / desktop entry
# ---------------------------------------------------------------------------

refresh_desktop_db() {
  command -v update-desktop-database >/dev/null 2>&1 &&
    update-desktop-database "$APP_DIR" 2>/dev/null || true
}

udev_rules_current() {
  local f
  for f in /etc/udev/rules.d/99-monsgeek.rules /usr/lib/udev/rules.d/99-monsgeek.rules; do
    [ -f "$f" ] && cmp -s "$RULES_SRC" "$f" && return 0
  done
  return 1
}

install_udev() {
  if udev_rules_current; then
    echo "udev rules already up to date."
    return 0
  fi
  echo "udev rules are missing or outdated; installing them needs sudo."
  if ! command -v sudo >/dev/null 2>&1; then
    warn "sudo not found. Install them manually:"
    echo "  install -m 644 $RULES_SRC /etc/udev/rules.d/99-monsgeek.rules" >&2
    return 0
  fi
  sudo install -D -m 644 "$RULES_SRC" /etc/udev/rules.d/99-monsgeek.rules
  sudo udevadm control --reload-rules
  sudo udevadm trigger --subsystem-match=hidraw --subsystem-match=input
  echo "udev rules installed. Reconnect the keyboard if it is not detected."
}

install_desktop_entry() {
  mkdir -p "$APP_DIR"
  # The packaged entry runs `iot_driver tui` from PATH; point it at this install
  # instead, since a desktop session's PATH often lacks ~/.local/bin.
  local exec_line line
  exec_line="Exec=$(desktop_quote "$BIN") tui"
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      Exec=*) printf '%s\n' "$exec_line" ;;
      *) printf '%s\n' "$line" ;;
    esac
  done <"$DRIVER_DIR/packaging/$DESKTOP_ID" >"$DESKTOP_FILE"
  chmod 644 "$DESKTOP_FILE"
  refresh_desktop_db
  echo "  $DESKTOP_FILE"
}

# ---------------------------------------------------------------------------
# Actions
# ---------------------------------------------------------------------------

do_install() {
  local mode="$AUTOSTART"
  [ "$mode" = auto ] && mode="$(detect_autostart)"
  if [ "$mode" = runit ] && [ -z "$(runit_layout)" ]; then
    echo "Unknown runit service layout (expected /etc/sv + /var/service or /etc/runit/sv + /run/runit/service)." >&2
    exit 1
  fi

  if [ "$BUILD" = 1 ]; then
    step "Building iot_driver (release)"
    command -v cargo >/dev/null 2>&1 || {
      echo "cargo not found. Install Rust (https://rustup.rs) or use --no-build." >&2
      exit 1
    }
    (cd "$DRIVER_DIR" && cargo build --release --bin iot_driver)
  fi
  [ -x "$BUILT_BIN" ] || {
    echo "Binary not found at $BUILT_BIN. Build it first or drop --no-build." >&2
    exit 1
  }

  step "Installing binaries to $BIN_DIR"
  mkdir -p "$BIN_DIR"
  # Copy then rename: replaces a symlink or a running binary atomically instead of
  # writing into it (which fails with "Text file busy" while the server runs).
  local tmp="$BIN_DIR/.iot_driver.new.$$"
  install -m 755 "$BUILT_BIN" "$tmp"
  mv -f "$tmp" "$BIN"
  echo "  $BIN"

  cat >"$LAUNCHER.new.$$" <<EOF
#!/bin/sh
# $MARKER - rerun it to update.
# No arguments opens the TUI; anything else is an iot_driver command.
[ \$# -eq 0 ] && exec "$BIN" tui
exec "$BIN" "\$@"
EOF
  chmod 755 "$LAUNCHER.new.$$"
  mv -f "$LAUNCHER.new.$$" "$LAUNCHER"
  echo "  $LAUNCHER"

  step "Installing device database to $DATA_DIR"
  DATA_DIR="$DATA_DIR" SKIP_REFRESH="${SKIP_REFRESH:-1}" "$REPO_ROOT/scripts/install-data.sh"

  step "Installing app menu entry"
  install_desktop_entry

  if [ "$UDEV" = 1 ]; then
    step "Checking udev rules"
    install_udev
  fi

  step "Setting up server autostart ($mode)"
  remove_autostart_except "$mode"
  case "$mode" in
    none)
      echo "  no automatic start (--autostart=none)"
      if [ "$START" = 1 ]; then
        kill_strays
        start_detached
      fi
      ;;
    *) "install_$mode" ;;
  esac

  step "Done"
  echo "  monsgeek            open the TUI"
  echo "  monsgeek <command>  run a CLI command (monsgeek --help)"
  echo "  App menu entry:     \"$(sed -n 's/^Name=//p' "$DESKTOP_FILE")\""
  echo "  Web configurator:   https://web.monsgeek.com (needs the server running)"
  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
      echo
      echo "NOTE: $BIN_DIR is not on your PATH. Add this to your shell profile:"
      echo "  export PATH=\"$BIN_DIR:\$PATH\""
      ;;
  esac
}

do_uninstall() {
  step "Removing server autostart"
  remove_autostart_except ""
  step "Stopping the server"
  kill_strays
  step "Removing installed files"
  local f
  for f in "$BIN" "$LAUNCHER" "$DESKTOP_FILE" \
    "$DATA_DIR/devices.json" "$DATA_DIR/device_matrices.json"; do
    if [ -e "$f" ] || [ -L "$f" ]; then
      rm -f "$f"
      echo "  removed $f"
    fi
  done
  rmdir "$DATA_DIR" 2>/dev/null || true
  refresh_desktop_db
  echo
  echo "The udev rules are system-wide and were left in place. To remove them:"
  echo "  sudo rm /etc/udev/rules.d/99-monsgeek.rules && sudo udevadm control --reload-rules"
}

main() {
  local arg
  for arg in "$@"; do
    case "$arg" in
      install | uninstall) ACTION="$arg" ;;
      --no-build) BUILD=0 ;;
      --no-start) START=0 ;;
      --no-udev) UDEV=0 ;;
      --autostart=*)
        AUTOSTART="${arg#--autostart=}"
        case "$AUTOSTART" in
          auto | systemd | runit | openrc | xdg | none) ;;
          *)
            echo "Invalid --autostart value: $AUTOSTART (auto, systemd, runit, openrc, xdg, none)" >&2
            exit 2
            ;;
        esac
        ;;
      -h | --help)
        sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d; s/^# \{0,1\}//'
        exit 0
        ;;
      *)
        echo "Unknown argument: $arg (see --help)" >&2
        exit 2
        ;;
    esac
  done

  if [ "$(id -u)" -eq 0 ]; then
    echo "Run this as your normal user, not root: it installs into your home directory" >&2
    echo "and asks for sudo itself when a system file needs changing." >&2
    exit 1
  fi

  case "$ACTION" in
    install) do_install ;;
    uninstall) do_uninstall ;;
  esac
}

# Sourcing the script (for tests) defines the functions without running anything.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  main "$@"
fi
